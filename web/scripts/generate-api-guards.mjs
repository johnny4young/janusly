/**
 * Generate runtime response guards from the public v1 OpenAPI document: one
 * `is<Component>` per shared schema and one `is<Operation>Response` per
 * operation with a 2xx payload. Every export is a pure function, so a bundle
 * keeps only the guards its call sites import.
 *
 * Guards check shape only (types, nullability, enums, required and closed
 * keys, integers). Length, item-count and numeric bounds are server policy:
 * they are accepted in the schema and never enforced in the browser.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { dataSchemaFor, payloadComponents, refComponentName } from "./generate-api-types.mjs";

const HEADER = `// GENERATED by scripts/generate-api-guards.mjs from contract/openapi.json.
// Do not edit: run \`make generate\` after changing the Go manifest.
`;

const ANNOTATIONS = new Set(["description", "summary", "title", "format"]);
const POLICY = new Set(["minimum", "maximum", "minLength", "maxLength", "minItems", "maxItems"]);
const STRUCTURAL = new Set([
  "type", "enum", "const", "required", "properties", "additionalProperties", "items",
  "anyOf", "oneOf", "allOf", "$ref",
]);
const OBJECT_KEYWORDS = ["properties", "required", "additionalProperties"];
const TYPES = new Set(["string", "number", "integer", "boolean", "null", "array", "object"]);
const PRIMITIVES = [
  "allOf", "anyOf", "arrayOf", "isAny", "isBoolean", "isFiniteNumber", "isInteger", "isNull", "isRecord",
  "isShape", "isString", "literal", "nullable", "recordOf", "shape",
];
const TYPE_GUARDS = {
  string: "isString", number: "isFiniteNumber", integer: "isInteger", boolean: "isBoolean", null: "isNull",
};

function isPlainObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function isPrimitive(value) {
  return value === null || ["string", "number", "boolean"].includes(typeof value);
}

function capitalize(text) {
  const clean = text.replace(/[^A-Za-z0-9]+(.)?/g, (_, next) => (next ? next.toUpperCase() : ""));
  return clean.charAt(0).toUpperCase() + clean.slice(1);
}

/** PascalCase guard stem for an operation, from its operationId. */
export function operationStem(operation, key) {
  const id = operation?.operationId;
  if (typeof id !== "string" || id === "") throw new Error(`${key}: operationId is required to name its guard`);
  const parts = id.split(/[_-]+/).filter(Boolean);
  // Operation keys drop the /v1 prefix, so the guard names do too.
  if (/^v\d+$/.test(parts[1] ?? "")) parts.splice(1, 1);
  return parts.map(capitalize).join("");
}

function matchesType(value, type) {
  switch (type) {
    case "string": return typeof value === "string";
    case "number": return typeof value === "number" && Number.isFinite(value);
    case "integer": return Number.isSafeInteger(value);
    case "boolean": return typeof value === "boolean";
    case "null": return value === null;
    default: return false;
  }
}

function propertyKey(key) {
  if (key === "__proto__") throw new Error(`property name ${key} cannot be described by an object literal`);
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

class GuardCompiler {
  constructor(components) {
    this.components = components;
  }

  validate(schema, where) {
    if (!isPlainObject(schema)) throw new Error(`${where}: schema must be an object`);
    for (const key of Object.keys(schema)) {
      if (!STRUCTURAL.has(key) && !POLICY.has(key) && !ANNOTATIONS.has(key)) {
        throw new Error(`${where}: unsupported keyword ${JSON.stringify(key)}`);
      }
    }
  }

  // An opaque fragment ({} or annotations only) accepts every JSON value; a
  // required key of that shape is still checked for presence.
  acceptsAnything(schema) {
    if (!isPlainObject(schema)) return false;
    if (Object.hasOwn(schema, "$ref")) {
      return this.acceptsAnything(this.components.get(refComponentName(schema.$ref, this.components)));
    }
    return Object.keys(schema).every((key) => ANNOTATIONS.has(key) || POLICY.has(key));
  }

  /** An expression evaluating to a one-argument guard for `schema`. */
  guard(schema, where, depth) {
    this.validate(schema, where);
    if (Object.hasOwn(schema, "$ref")) {
      const siblings = Object.keys(schema).filter((key) => key !== "$ref" && !ANNOTATIONS.has(key));
      if (siblings.length > 0) throw new Error(`${where}: $ref cannot be combined with ${siblings.join(", ")}`);
      const name = refComponentName(schema.$ref, this.components);
      return this.acceptsAnything(this.components.get(name)) ? "isAny" : `is${name}`;
    }
    const parts = [];
    let literals = null;
    if (Object.hasOwn(schema, "const")) {
      if (!isPrimitive(schema.const)) throw new Error(`${where}: const must be a JSON primitive`);
      literals = [schema.const];
    }
    if (Object.hasOwn(schema, "enum")) {
      if (!Array.isArray(schema.enum) || !schema.enum.every(isPrimitive)) {
        throw new Error(`${where}: enum must list JSON primitives`);
      }
      literals = literals ? literals.filter((value) => schema.enum.includes(value)) : schema.enum;
    }
    if (literals) parts.push(`literal(${literals.map((value) => JSON.stringify(value)).join(", ")})`);
    if (schema.type !== undefined) {
      const types = Array.isArray(schema.type) ? schema.type : [schema.type];
      if (types.length === 0) throw new Error(`${where}: type must name at least one type`);
      for (const type of types) {
        if (!TYPES.has(type)) throw new Error(`${where}: unsupported type ${JSON.stringify(type)}`);
      }
      const implied = literals && literals.every((value) => types.some((type) => matchesType(value, type)));
      if (!implied) parts.push(this.typeGuard(schema, types, where, depth));
    } else if (this.hasObjectKeywords(schema) || schema.items !== undefined) {
      throw new Error(`${where}: object and array keywords need a type`);
    }
    for (const keyword of ["anyOf", "oneOf", "allOf"]) {
      if (!Object.hasOwn(schema, keyword)) continue;
      const branches = schema[keyword];
      if (!Array.isArray(branches) || branches.length === 0) {
        throw new Error(`${where}: ${keyword} must list at least one schema`);
      }
      // Manifest oneOf branches are disjoint closed shapes, so any match is the match.
      const guards = branches.map((branch, index) => this.guard(branch, `${where}/${keyword}/${index}`, depth));
      parts.push(keyword === "allOf" ? this.all(guards) : this.any(guards));
    }
    return this.all(parts);
  }

  all(guards) {
    const kept = guards.filter((guard) => guard !== "isAny");
    if (kept.length === 0) return "isAny";
    return kept.length === 1 ? kept[0] : `allOf(${kept.join(", ")})`;
  }

  any(guards) {
    if (guards.includes("isAny")) return "isAny";
    const unique = [...new Set(guards)];
    const others = unique.filter((guard) => guard !== "isNull");
    if (others.length === 0) return "isNull";
    if (others.length < unique.length) {
      const inner = others.length === 1 ? others[0] : `anyOf(${others.join(", ")})`;
      return `nullable(${inner})`;
    }
    return others.length === 1 ? others[0] : `anyOf(${others.join(", ")})`;
  }

  hasObjectKeywords(schema) {
    return (isPlainObject(schema.properties) && Object.keys(schema.properties).length > 0)
      || (Array.isArray(schema.required) && schema.required.length > 0)
      || (schema.additionalProperties !== undefined && schema.additionalProperties !== true);
  }

  typeGuard(schema, types, where, depth) {
    return this.any(types.map((type) => {
      if (type === "array") {
        if (schema.items === undefined) return "Array.isArray";
        if (!isPlainObject(schema.items)) throw new Error(`${where}/items: tuple items are not supported`);
        const item = this.guard(schema.items, `${where}/items`, depth);
        return item === "isAny" ? "Array.isArray" : `arrayOf(${item})`;
      }
      if (type === "object") {
        return this.hasObjectKeywords(schema) ? this.shape(schema, where, depth, "shape") : "isRecord";
      }
      return TYPE_GUARDS[type];
    }));
  }

  /** `shape(required, optional, rest)` or, as a call, `isShape(value, ...)`. */
  shape(schema, where, depth, callee) {
    const properties = schema.properties ?? {};
    if (!isPlainObject(properties)) throw new Error(`${where}/properties: must be an object`);
    const required = schema.required ?? [];
    if (!Array.isArray(required) || !required.every((key) => typeof key === "string")) {
      throw new Error(`${where}/required: must list property names`);
    }
    const additional = schema.additionalProperties;
    if (additional !== undefined && typeof additional !== "boolean" && !isPlainObject(additional)) {
      throw new Error(`${where}/additionalProperties: must be a boolean or a schema`);
    }
    const rest = additional === false ? null
      : isPlainObject(additional) ? this.guard(additional, `${where}/additionalProperties`, depth + 1)
        : "true";
    const keys = [...new Set([...Object.keys(properties), ...required])].sort();
    if (keys.length === 0 && rest !== null && rest !== "true") {
      return callee === "shape" ? `recordOf(${rest})` : null;
    }
    const pad = "  ".repeat(depth + 1);
    const describe = (list) => (list.length === 0 ? "{}" : `{\n${list.map((key) => {
      const guard = Object.hasOwn(properties, key)
        ? this.guard(properties[key], `${where}/properties/${key}`, depth + 1)
        : "isAny";
      return `${pad}${propertyKey(key)}: ${guard},`;
    }).join("\n")}\n${"  ".repeat(depth)}}`);
    const requiredSet = new Set(required);
    const args = [describe(keys.filter((key) => requiredSet.has(key)))];
    const optional = keys.filter((key) => !requiredSet.has(key));
    if (optional.length > 0 || rest !== null) args.push(describe(optional));
    if (rest !== null) args.push(rest === "isAny" ? "true" : rest);
    return callee === "shape" ? `shape(${args.join(", ")})` : `isShape(value, ${args.join(", ")})`;
  }

  functionBody(schema, where) {
    this.validate(schema, where);
    const pureObject = schema.type === "object" && this.hasObjectKeywords(schema)
      && Object.keys(schema).every((key) => key === "type" || OBJECT_KEYWORDS.includes(key)
        || ANNOTATIONS.has(key) || POLICY.has(key));
    const direct = pureObject ? this.shape(schema, where, 1, "isShape") : null;
    if (direct) return `  return ${direct}`;
    const guard = this.guard(schema, where, 1);
    return guard === "isAny" ? "  return true" : `  return ${guard}(value)`;
  }
}

function operationsOf(document) {
  const operations = [];
  for (const [routePath, items] of Object.entries(document?.paths ?? {})) {
    for (const [method, operation] of Object.entries(items)) {
      const data = dataSchemaFor(operation);
      if (!data) continue;
      const key = `${method.toUpperCase()} ${routePath}`;
      operations.push({ key, stem: operationStem(operation, key), data });
    }
  }
  return operations.sort((left, right) => left.key.localeCompare(right.key));
}

/** Render the guard module for one contract document. */
export function generateGuards(document) {
  const components = payloadComponents(document);
  const operations = operationsOf(document);
  const componentNames = [...components.keys()].sort();
  const names = new Set([...PRIMITIVES, ...componentNames.map((name) => `is${name}`)]);
  for (const { key, stem } of operations) {
    const name = `is${stem}Response`;
    if (names.has(name)) throw new Error(`${key}: guard name ${name} collides with another guard`);
    names.add(name);
  }
  const compiler = new GuardCompiler(components);

  const exported = [];
  for (const name of componentNames) {
    const body = compiler.functionBody(components.get(name), `#/components/schemas/${name}`);
    // An opaque fragment never reads its argument.
    const parameter = body === "  return true" ? "_value" : "value";
    exported.push(`export function is${name}(${parameter}: unknown): ${parameter} is Api.${name} {\n${body}\n}\n`);
  }
  for (const { key, stem, data } of operations) {
    const body = compiler.functionBody(data, `${key} response`);
    exported.push(`/** ${key} */\nexport function is${stem}Response(value: unknown): value is Api.ApiResponses[${JSON.stringify(key)}] {\n${body}\n}\n`);
  }
  const body = exported.join("\n");
  const imports = PRIMITIVES.filter((name) => new RegExp(`\\b${name}\\b`).test(body));
  const importLine = imports.length > 0 ? `import { ${imports.join(", ")} } from "./guards"\n` : "";
  return `${HEADER}
import type * as Api from "./api-types.generated"
${importLine}
${body}`;
}

function isMainModule() {
  return process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
}

export const CONTRACT_PATH = "../contract/openapi.json";
export const OUTPUT_PATH = "src/lib/api-guards.generated.ts";

if (isMainModule()) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const document = JSON.parse(fs.readFileSync(path.join(root, CONTRACT_PATH), "utf8"));
  const output = generateGuards(document);
  fs.writeFileSync(path.join(root, OUTPUT_PATH), output);
  const operations = (output.match(/^\/\*\* [A-Z]+ \//gm) ?? []).length;
  const components = (output.match(/^export function /gm) ?? []).length - operations;
  console.log(`api guards generated (${components} components, ${operations} operations).`);
}
