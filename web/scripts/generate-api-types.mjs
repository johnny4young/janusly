/**
 * Generate the TypeScript wire contract from the public v1 OpenAPI document.
 *
 * Response payloads, request bodies, normalized error envelopes, and success
 * status codes all come from the Go-owned manifest. A declared operation must
 * therefore compile at the call site without a hand-written `as` assertion.
 * Every payload component becomes a named type that operations reference.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HEADER = `// GENERATED by scripts/generate-api-types.mjs from contract/openapi.json.
// Do not edit: run \`make generate\` after changing the Go manifest.
`;

const COMPONENT_PREFIX = "#/components/schemas/";

// Transport envelopes are unwrapped by api(), so they never become payload types.
const ENVELOPE_COMPONENTS = new Set(["V1Envelope", "V1ErrorEnvelope"]);

const RESERVED_NAMES = new Set([
  "JsonPrimitive", "JsonValue", "BrowserApiError", "ApiRequests", "ApiResponses",
  "ApiSuccessStatuses", "ApiOperation", "ApiRequest", "ApiResponse",
  "ApiSuccessStatus", "ApiErrorResponse",
]);

const baseRefNames = new Map([
  [`${COMPONENT_PREFIX}JsonValue`, "JsonValue"],
  // api() normalizes the versioned error envelope to this same shape.
  [`${COMPONENT_PREFIX}V1ErrorEnvelope`, "BrowserApiError"],
]);

/** Payload components by name, excluding the transport envelopes. */
export function payloadComponents(...documents) {
  const components = new Map();
  for (const document of documents) {
    for (const [name, schema] of Object.entries(document?.components?.schemas ?? {})) {
      if (ENVELOPE_COMPONENTS.has(name)) continue;
      if (!/^[A-Z][A-Za-z0-9]*$/.test(name) || RESERVED_NAMES.has(name)) {
        throw new Error(`component name ${JSON.stringify(name)} is not a usable TypeScript type name`);
      }
      const previous = components.get(name);
      if (previous && JSON.stringify(previous) !== JSON.stringify(schema)) {
        throw new Error(`component ${name} differs between contract documents`);
      }
      components.set(name, schema);
    }
  }
  assertAcyclic(components);
  return components;
}

/** The component a local $ref names; any other reference is an error. */
export function refComponentName(ref, components) {
  if (typeof ref !== "string" || !ref.startsWith(COMPONENT_PREFIX)) {
    throw new Error(`unsupported $ref ${JSON.stringify(ref)}`);
  }
  const name = ref.slice(COMPONENT_PREFIX.length);
  if (!components.has(name)) throw new Error(`$ref ${ref} names no component`);
  return name;
}

function collectRefs(schema, out = new Set()) {
  if (Array.isArray(schema)) {
    for (const item of schema) collectRefs(item, out);
  } else if (schema && typeof schema === "object") {
    if (typeof schema.$ref === "string") out.add(schema.$ref);
    for (const value of Object.values(schema)) collectRefs(value, out);
  }
  return out;
}

// Recursive components would need recursive guards and self-referential
// aliases; the manifest has none, so a cycle is rejected rather than guessed at.
function assertAcyclic(components) {
  const state = new Map();
  const visit = (name, trail) => {
    if (state.get(name) === "done") return;
    if (state.get(name) === "active") {
      throw new Error(`component reference cycle: ${[...trail, name].join(" -> ")}`);
    }
    state.set(name, "active");
    for (const ref of collectRefs(components.get(name))) {
      if (baseRefNames.has(ref)) continue;
      visit(refComponentName(ref, components), [...trail, name]);
    }
    state.set(name, "done");
  };
  for (const name of [...components.keys()].sort()) visit(name, []);
}

function refNamesFor(components) {
  const names = new Map(baseRefNames);
  for (const name of components.keys()) names.set(`${COMPONENT_PREFIX}${name}`, name);
  return names;
}

const defaultRefNames = baseRefNames;

function union(types) {
  return [...new Set(types)].join(" | ");
}

const typescriptNeverSchema = { "x-typescript-never": true };

function flattenPureOneOfBranches(branches) {
  return branches.flatMap((branch) => {
    if (branch && typeof branch === "object" && Object.keys(branch).length === 1 && Array.isArray(branch.oneOf)) {
      return flattenPureOneOfBranches(branch.oneOf);
    }
    return [branch];
  });
}

function exclusiveClosedObjectUnion(branches, indent, refs) {
  if (!branches.every((branch) =>
    branch?.type === "object"
    && branch.additionalProperties === false
    && branch.properties
    && typeof branch.properties === "object"
    && !Array.isArray(branch.properties))) {
    return null;
  }
  const allKeys = new Set(branches.flatMap((branch) => Object.keys(branch.properties)));
  return union(branches.map((branch) => {
    const forbidden = Object.fromEntries(
      [...allKeys]
        .filter((key) => !Object.hasOwn(branch.properties, key))
        .map((key) => [key, typescriptNeverSchema]),
    );
    return schemaToType({
      ...branch,
      properties: { ...branch.properties, ...forbidden },
    }, indent, refs);
  }));
}

/** Convert one JSON-Schema fragment to a TypeScript type expression. */
export function schemaToType(schema, indent = 0, refs = defaultRefNames) {
  if (!schema || typeof schema !== "object") return "unknown";
  if (schema["x-typescript-never"] === true) return "never";
  if (typeof schema.$ref === "string") {
    const name = refs.get(schema.$ref);
    if (!name) throw new Error(`unresolved $ref ${schema.$ref}`);
    return name;
  }
  if (Object.hasOwn(schema, "const")) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum) && schema.enum.length > 0) {
    return union(schema.enum.map((value) => JSON.stringify(value)));
  }
  if (Array.isArray(schema.oneOf)) {
    const branches = flattenPureOneOfBranches(schema.oneOf);
    return exclusiveClosedObjectUnion(branches, indent, refs)
      ?? union(branches.map((one) => schemaToType(one, indent, refs)));
  }
  if (Array.isArray(schema.anyOf)) {
    return union(schema.anyOf.map((one) => schemaToType(one, indent, refs)));
  }
  if (Array.isArray(schema.allOf)) {
    return [...new Set(schema.allOf.map((one) => schemaToType(one, indent, refs)))].join(" & ");
  }

  // The manifest emits nullable scalars as {"type": ["string", "null"]}.
  if (Array.isArray(schema.type)) {
    return union(schema.type.map((one) => schemaToType({ ...schema, type: one }, indent, refs)));
  }

  switch (schema.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      const item = schemaToType(schema.items, indent, refs);
      return item.includes(" | ") || item.includes(" & ") ? `(${item})[]` : `${item}[]`;
    }
    case "object": {
      const properties = schema.properties;
      const additional = schema.additionalProperties;
      if (!properties || Object.keys(properties).length === 0) {
        if (additional && typeof additional === "object") {
          return `Record<string, ${schemaToType(additional, indent + 1, refs)}>`;
        }
        // Existing operations outside the current closure bands may still be
        // explicitly opaque. New/tightened operations are tested not to use it.
        return "Record<string, unknown>";
      }
      const required = new Set(schema.required ?? []);
      const pad = "  ".repeat(indent + 1);
      const lines = Object.entries(properties).map(([key, value]) => {
        const optional = required.has(key) ? "" : "?";
        return `${pad}${JSON.stringify(key)}${optional}: ${schemaToType(value, indent + 1, refs)}`;
      });
      const declared = `{\n${lines.join("\n")}\n${"  ".repeat(indent)}}`;
      if (additional && typeof additional === "object") {
        return `${declared} & Record<string, ${schemaToType(additional, indent + 1, refs)}>`;
      }
      return declared;
    }
    default:
      return "unknown";
  }
}

function jsonResponseSchemas(operation) {
  return Object.entries(operation?.responses ?? {})
    .filter(([status]) => /^2\d\d$/.test(status))
    .sort(([left], [right]) => Number(left) - Number(right))
    .map(([, response]) => response?.content?.["application/json"]?.schema)
    .filter(Boolean);
}

function unwrapDataSchema(schema) {
  if (!Array.isArray(schema?.allOf)) return schema;
  for (const part of schema.allOf) {
    const data = part?.properties?.data;
    if (data) return data;
  }
  return null;
}

/** Pull the payload schema from every declared 2xx JSON response. */
export function dataSchemaFor(operation) {
  const schemas = jsonResponseSchemas(operation).map(unwrapDataSchema).filter(Boolean);
  if (schemas.length === 0) return null;
  const unique = [...new Map(schemas.map((schema) => [JSON.stringify(schema), schema])).values()];
  return unique.length === 1 ? unique[0] : { oneOf: unique };
}

/** Pull the JSON request body schema, or null for bodyless operations. */
export function requestSchemaFor(operation) {
  return operation?.requestBody?.content?.["application/json"]?.schema ?? null;
}

function successStatusesFor(operation) {
  return Object.keys(operation?.responses ?? {})
    .filter((status) => /^2\d\d$/.test(status))
    .map(Number)
    .sort((left, right) => left - right);
}

export function generate(...documents) {
  const components = payloadComponents(...documents);
  const refs = refNamesFor(components);
  const byKey = new Map();
  for (const document of documents) {
    for (const [routePath, operations] of Object.entries(document?.paths ?? {})) {
      for (const [method, operation] of Object.entries(operations)) {
        const data = dataSchemaFor(operation);
        if (!data) continue;
        const key = `${method.toUpperCase()} ${routePath}`;
        const entry = byKey.get(key) ?? {
          key,
          summary: operation.summary ?? "",
          responseTypes: new Set(),
          requestTypes: new Set(),
          statuses: new Set(),
        };
        entry.responseTypes.add(schemaToType(data, 1, refs));
        const request = requestSchemaFor(operation);
        entry.requestTypes.add(request ? schemaToType(request, 1, refs) : "undefined");
        for (const status of successStatusesFor(operation)) entry.statuses.add(status);
        byKey.set(key, entry);
      }
    }
  }
  const entries = [...byKey.values()].sort((a, b) => a.key.localeCompare(b.key));

  const emit = (render) => entries
    .map((entry) => `  /** ${entry.summary} */\n  ${JSON.stringify(entry.key)}: ${render(entry)}`)
    .join("\n");
  const responses = emit((entry) => union([...entry.responseTypes]));
  const requests = emit((entry) => union([...entry.requestTypes]));
  const statuses = emit((entry) => union([...entry.statuses].sort((a, b) => a - b)));
  const componentTypes = [...components.keys()].sort().map((name) =>
    `export type ${name} = ${schemaToType(components.get(name), 0, refs)}\n`).join("\n");

  return `${HEADER}
export type JsonPrimitive = string | number | boolean | null
export type JsonValue = JsonPrimitive | JsonValue[] | { [key: string]: JsonValue }

/** Normalized non-2xx payload thrown by api() for every JSON operation. */
export type BrowserApiError = {
  error?: string
  code?: string
  params?: Record<string, unknown>
}
${componentTypes ? `\n${componentTypes}` : ""}
/** JSON request bodies by operation; bodyless operations resolve to undefined. */
export interface ApiRequests {
${requests}
}

/** Parsed payloads by operation, after any v1 envelope is unwrapped. */
export interface ApiResponses {
${responses}
}

/** Successful HTTP status codes declared for each operation. */
export interface ApiSuccessStatuses {
${statuses}
}

export type ApiOperation = keyof ApiResponses
export type ApiRequest<Operation extends ApiOperation> = ApiRequests[Operation]
export type ApiResponse<Operation extends ApiOperation> = ApiResponses[Operation]
export type ApiSuccessStatus<Operation extends ApiOperation> = ApiSuccessStatuses[Operation]
export type ApiErrorResponse<Operation extends ApiOperation> = Operation extends ApiOperation ? BrowserApiError : never
`;
}

function isMainModule() {
  return process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
}

export const CONTRACT_PATH = "../contract/openapi.json";
export const OUTPUT_PATH = "src/lib/api-types.generated.ts";

if (isMainModule()) {
  const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const read = (relative) =>
    JSON.parse(fs.readFileSync(path.join(repositoryRoot, relative), "utf8"));
  const output = generate(read(CONTRACT_PATH));
  fs.writeFileSync(path.join(repositoryRoot, OUTPUT_PATH), output);
  const count = (output.match(/^  "[A-Z]+ /gm) ?? []).length / 3;
  console.log(`api types generated (${count} operations).`);
}
