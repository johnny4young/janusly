/**
 * Generate the `.d.ts` entry barrel the design-sync converter needs.
 *
 * `lib/dts.mjs` extracts a component's props two ways:
 *   1. a named `<Name>Props` interface/type alias found anywhere in the
 *      declaration tree, or
 *   2. failing that, the first call signature of the component's exported
 *      declaration — looked up in the package's `.d.ts` *entry* module.
 *
 * Janusly's components mostly use inline anonymous prop objects
 * (`function QueueLagChip({ health }: { health: QueueHealth | null })`), so
 * path 1 misses them and path 2 is the one that matters. Path 2 resolves
 * `join(pkgDir, pkgJson.types ?? 'index.d.ts')`, and `web/` publishes no
 * types field — so without this file the lookup hits a missing module and
 * every such component emits `{ [key: string]: unknown }`, leaving the design
 * agent with no API contract at all.
 *
 * Emitting the barrel at `web/index.d.ts` (generated, gitignored) fixes path 2
 * without touching the application's own `package.json`.
 *
 * Run from `web/`, after the declaration emit. Part of `cfg.buildCmd`.
 */

import { readdirSync, writeFileSync, existsSync } from 'node:fs'
import { join, relative } from 'node:path'

const TYPES_ROOT = 'types/src'
const OUT = 'index.d.ts'

if (!existsSync(TYPES_ROOT)) {
  console.error(`[barrel] ${TYPES_ROOT} missing — run the declaration emit first`)
  process.exit(1)
}

/** Every emitted declaration whose source was a `.tsx` (i.e. a component module). */
function walk(dir, acc = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (e.isDirectory()) walk(p, acc)
    else if (e.name.endsWith('.d.ts')) acc.push(p)
  }
  return acc
}

const decls = walk(TYPES_ROOT)
  // Only modules that came from a `.tsx` carry components. Everything else is
  // helpers/types that would widen the export surface without adding cards.
  .filter((p) => existsSync(join('src', relative(TYPES_ROOT, p).replace(/\.d\.ts$/, '.tsx'))))
  // Tests and story-less harness files never contribute components.
  .filter((p) => !/\.(test|browser\.test)\.d\.ts$/.test(p))
  // Application entry modules are excluded from the bundle entry too — see
  // .design-sync/overrides/source-kit.mjs. Keep the two lists in step.
  .filter((p) => !/(^|[\\/])main\.d\.ts$/.test(p))
  .sort()

const lines = decls.map((p) => `export * from './${p.replace(/\.d\.ts$/, '')}';`)

writeFileSync(OUT, `${[
  '// GENERATED by .design-sync/gen-dts-barrel.mjs — do not edit, do not commit.',
  '// Entry module for the design-sync .d.ts prop extractor. See that script.',
  ...lines,
].join('\n')}\n`)

console.error(`[barrel] ${OUT}: ${decls.length} component module(s) re-exported`)
